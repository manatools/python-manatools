def _png(width, height, pixel):
    """Encode an RGB PNG; pixel(x, y) returns an (r, g, b) tuple."""
    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xffffffff)
    rows = []
    for y in range(height):
        rows.append(b"\x00" + b"".join(bytes(pixel(x, y)) for x in range(width)))
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(b"".join(rows), 9))
            + chunk(b"IEND", b""))


def _logo(x, y):
    """48x48 badge: blue disc with a white ring on a light background."""
    d = ((x - 23.5) ** 2 + (y - 23.5) ** 2) ** 0.5
    if d < 14:
        return (32, 96, 192)
    if d < 18:
        return (255, 255, 255)
    if d < 22:
        return (32, 96, 192)
    return (238, 242, 250)


_BARS = [(38, (70, 130, 220)), (55, (70, 130, 220)), (47, (70, 130, 220)),
         (72, (70, 130, 220)), (88, (240, 140, 40)), (64, (70, 130, 220))]


def _chart(x, y):
    """320x140 bar chart, last-but-one bar highlighted."""
    height, base = 140, 128
    if y == base:
        return (90, 90, 90)
    slot = (x - 16) // 50
    inside = 0 <= slot < len(_BARS) and 16 + slot * 50 + 8 <= x < 16 + slot * 50 + 42
    if inside:
        bar_h, color = _BARS[slot]
        if base - bar_h <= y < base:
            return color
    if y % 32 == 0 and y < base:
        return (225, 225, 225)
    return (255, 255, 255)


def _avatar(x, y):
    """40x40 round avatar."""
    d = ((x - 19.5) ** 2 + (y - 19.5) ** 2) ** 0.5
    if d < 7 and y < 22:
        return (250, 220, 190)
    if d < 19:
        return (60, 160, 120)
    return (255, 255, 255)


def _stripe(x, y):
    """600x6 gradient rule, inlined as a data: URI (no resolver needed)."""
    t = x / 599.0
    return (int(32 + 208 * t), int(96 + 44 * t), int(192 - 152 * t))


