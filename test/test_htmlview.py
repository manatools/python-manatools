def _large_table(rows=1000):
    out = ['<h2>Large table</h2><p>%d rows, zebra striped; scroll to test rendering speed.</p>' % rows,
           '<table border="0" cellpadding="3" cellspacing="0" width="100%">',
           '<tr style="background:#2060c0;color:#fff"><th>#</th><th>Package</th><th>Version</th>'
           '<th>Size</th><th>Status</th></tr>']
    for i in range(1, rows + 1):
        bg = "#f6f8fc" if i % 2 else "#ffffff"
        status = ('<span style="color:#1c7a4a">installed</span>' if i % 3
                  else '<a href="https://example.org/pkg/%d">update available</a>' % i)
        out.append(f'<tr style="background:{bg}"><td align="right">{i}</td><td>package-{i:04d}</td>'
                   f'<td>1.{i % 17}.{i % 5}</td><td align="right">{(i * 37) % 900 + 12} KiB</td>'
                   f'<td>{status}</td></tr>')
    out.append('</table>')
    return "".join(out)


SAMPLES = [
    ("Newsletter", NEWSLETTER, yui.YHtmlBasePolicy.NoBase),
    ("Conversation", CONVERSATION, yui.YHtmlBasePolicy.NoBase),
    ("Release notes", RELEASE_NOTES, yui.YHtmlBasePolicy.DocumentBase),
    ("Hostile", HOSTILE, yui.YHtmlBasePolicy.NoBase),
    ("Large table", _large_table(), yui.YHtmlBasePolicy.NoBase),
]


def test_htmlview_example(backend_name=None):
    if backend_name:
        os.environ['MUI_BACKEND'] = backend_name

    # Ensure fresh YUI detection
    YUI._instance = None
    YUI._backend = None

    ui = YUI_ui()
    factory = ui.widgetFactory()

    try:
        backend = YUI.backend()
        root_logger.debug("test_htmlview_example: program=%s backend=%s", os.path.basename(sys.argv[0]), getattr(backend, 'value', str(backend)))
    except Exception:
        root_logger.debug("test_htmlview_example: program=%s backend=unknown", os.path.basename(sys.argv[0]))

    dlg = factory.createMainDialog()
    vbox = factory.createVBox(dlg)
    factory.createHeading(vbox, "HtmlView Example")

    top = factory.createHBox(vbox)
    sample_combo = factory.createComboBox(top, "&Sample:", False)
    sample_combo.addItems([yui.YItem(name, selected=(i == 0)) for i, (name, _, _) in enumerate(SAMPLES)])
    sample_combo.setNotify(True)
    allow_remote = factory.createCheckBox(top, "&Allow remote content", False)
    allow_remote.setNotify(True)

    view = factory.createHtmlView(vbox)
    view.setCidResolver(CID_PARTS.get)
    view.setHelpText("Untrusted HTML, sanitized")
    view.setWeight(yui.YUIDimension.YD_VERT, 1)

    status_label = factory.createLabel(vbox, "")
    link_label = factory.createLabel(vbox, "Last link: (none)")

    def show_sample(name):
        for sample_name, html, policy in SAMPLES:
            if sample_name == name:
                view.setHtml(html, policy)
                root_logger.info("Showing sample %s (%d chars, policy %s)", name, len(html), policy.name)
                break
        update_status()

    def update_status():
        if view.allowRemote():
            remote = "allowed"
        elif view.remoteContentBlocked():
            remote = "blocked"
        else:
            remote = "none requested"
        status_label.setValue(f"Remote content: {remote}  |  base policy: {view.basePolicy().name}")

    show_sample(SAMPLES[0][0])

    ctrl_h = factory.createHBox(vbox)
    ok_btn = factory.createPushButton(ctrl_h, "&OK")

    root_logger.info("Opening HtmlView example dialog...")

    while True:
        ev = dlg.waitForEvent()
        et = ev.eventType()
        if et == yui.YEventType.CancelEvent:
            dlg.destroy()
            break
        elif et == yui.YEventType.WidgetEvent:
            w = ev.widget()
            if w == ok_btn and ev.reason() == yui.YEventReason.Activated:
                dlg.destroy()
                break
            elif w == view and ev.reason() == yui.YEventReason.Activated:
                url = view.lastActivatedUrl() or '(none)'
                link_label.setValue(f"Last link: {url}")
                root_logger.info("Link activated: %s", url)
            elif w == allow_remote:
                view.setAllowRemote(allow_remote.isChecked())
                update_status()
            elif w == sample_combo:
                show_sample(sample_combo.value())

    root_logger.info("Dialog closed")


if __name__ == '__main__':
    if len(sys.argv) > 1:
        test_htmlview_example(sys.argv[1])
    else:
        test_htmlview_example()
