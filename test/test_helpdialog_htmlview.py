def _demo_png(size=48):
  '''
  returns a small RGBA PNG (gradient disc) built in memory
  '''
  center = (size - 1) / 2
  raw = bytearray()
  for y in range(size):
    raw.append(0)
    for x in range(size):
      if ((x - center) ** 2 + (y - center) ** 2) ** 0.5 <= center:
        raw += bytes((40 + 150 * x // size, 110, 200 - 120 * y // size, 255))
      else:
        raw += b'\0\0\0\0'

  def chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff)

  return (b'\x89PNG\r\n\x1a\n'
          + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0))
          + chunk(b'IDAT', zlib.compress(bytes(raw)))
          + chunk(b'IEND', b''))


